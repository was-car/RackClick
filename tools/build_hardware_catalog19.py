def pretty(value):
    return (json.dumps(value,indent=2,ensure_ascii=True,allow_nan=False)+'\n').encode('ascii')

def literal(value):
    if value is None:return 'NULL'
    if type(value) is bool:return 'true' if value else 'false'
    if type(value) in (int,float):return str(value)
    c.require(isinstance(value,str),'aruba_sql_value_invalid')
    return "E'"+value.replace('\\','\\\\').replace("'","''")+"'"

def sql_source(model,digest):
    lines=['-- Auto-generated by tools/build_hardware_catalog19.py; SQL001-018 are frozen.',
      '-- Retain all existing immutable/publication triggers and runtime grants.',
      'ALTER TABLE hardware_group_template DROP CONSTRAINT hardware_group_template_type_check;',
      "ALTER TABLE hardware_group_template ADD CONSTRAINT hardware_group_template_type_check CHECK(type IN ('rj45','sfp','power'));",
      "ALTER TABLE hardware_group_template ADD COLUMN power_role text NOT NULL DEFAULT 'unspecified' CHECK(power_role IN ('unspecified','inlet','outlet'));",
      "ALTER TABLE hardware_group_template ADD CONSTRAINT hardware_group_power_role CHECK(type='power' OR power_role='unspecified');"]
    def insert(table,columns,values):lines.append('INSERT INTO '+table+' ('+columns+') VALUES ('+', '.join(map(literal,values))+');')
    pair=[model['key'],model['revision']];d=model['dimensionsMm']
    insert('hardware_definition','profile_key, revision, mount_kind, rack_units, width_mm, height_mm, depth_mm, color, definition_sha256, manufacturer, family, model, sku, provenance_kind, source_reference, sealed',pair+[model['kind'],model['rackUnits'],d['width'],d['height'],d['depth'],model['color'],digest]+[model['identity'][key] for key in ('manufacturer','family','model','sku')]+[model['provenance']['kind'],model['provenance']['source'],False])
    for order,g in enumerate(model['groups']):
        insert('hardware_group_template','profile_key, revision, group_key, sort_order, type, port_count, face, name, prefix, power_role',pair+[g['key'],order,g['type'],g['count'],g['face'],g['name'],g['prefix'],g['powerRole']])
    lines.append('UPDATE hardware_definition SET sealed=true WHERE profile_key='+literal(pair[0])+' AND revision='+literal(pair[1])+';')
    return ('\n'.join(lines)+'\n').encode('utf-8')

def targets_source(inputs):
    lines=['<!-- Auto-generated by tools/build_hardware_catalog19.py. -->','<Project>','  <Target Name="VerifyArubaHardwareCatalog" BeforeTargets="CoreCompile">','    <ItemGroup>']
    for name,digest in inputs.items():lines.append('      <_ArubaCatalogInput Include="$(MSBuildThisFileDirectory)../../../../'+name+'"><ExpectedHash>'+digest+'</ExpectedHash></_ArubaCatalogInput>')
    lines+=['    </ItemGroup>',
      '    <Error Condition="!Exists(\'%(_ArubaCatalogInput.Identity)\')" Code="aruba_catalog_stale" Text="aruba_catalog_stale: run tools/build_hardware_catalog19.py --check" />',
      '    <GetFileHash Files="@(_ArubaCatalogInput)" Algorithm="SHA256"><Output TaskParameter="Items" ItemName="_ArubaCatalogHashed" /></GetFileHash>',
      '    <Error Condition="\'%(_ArubaCatalogHashed.FileHash)\' != \'%(_ArubaCatalogHashed.ExpectedHash)\'" Code="aruba_catalog_stale" Text="aruba_catalog_stale: run tools/build_hardware_catalog19.py --check" />',
      '  </Target>','</Project>','']
    return '\n'.join(lines).encode('ascii')

def compile_catalog(root):
    raw={name:c.path(root,name).read_bytes() for name in (SOURCE,FACTS,LOCK,BASE)}
    source=c.load(raw[SOURCE]);facts=c.load(raw[FACTS]);lock=c.load(raw[LOCK])
    c.fields(lock,'formatVersion targetSchema sourceSha256 factsSha256 baseMigrationSha256 definitions state','aruba_lock_invalid')
    c.require(type(lock['formatVersion']) is int and lock['formatVersion']==1 and type(lock['targetSchema']) is int and lock['targetSchema']==19 and lock['state']==STATE,'aruba_target_unsupported')
    for name,field in ((SOURCE,'sourceSha256'),(FACTS,'factsSha256'),(BASE,'baseMigrationSha256')):c.require(c.sha(raw[name])==lock[field],'aruba_input_changed')
    # Narrow publication profile: repinning a new model/role/source is not review.
    c.require(c.canonical(source)==c.canonical(EXPECTED_SOURCE),'aruba_model_not_reviewed')
    c.require(c.canonical(facts)==c.canonical(EXPECTED_FACTS),'aruba_facts_mismatch')
    model=source['definitions'][0];pins=[dict(key=model['key'],revision=model['revision'],sha256=c.sha(c.canonical(model)))]
    c.require(lock['definitions']==pins,'aruba_definition_not_reviewed')
    server=c.server_source(source,commercial=True).decode('ascii').replace('tools/build_hardware_catalog.py;','tools/build_hardware_catalog19.py;').replace('internal static class CommercialHardwareProfiles','internal static class ArubaHardwareProfiles')
    old='new("rear-power", "power", 1, "rear", "AC inlet", "AC ")'
    c.require(server.count(old)==1,'aruba_server_template_invalid')
    server=server.replace(old,old+' { PowerRole = "inlet" }')
    view=c.projection(source);view['synthetic']=False
    for row,m in zip(view['profiles'],source['definitions']):
        row.update(identity=m['identity'],source=m['provenance']['source'])
        for g,original in zip(row['groups'],m['groups']):g['powerRole']=original['powerRole']
    outputs={SERVER:server.encode('ascii'),FRONTEND:pretty(view),SQL:sql_source(model,pins[0]['sha256'])}
    inputs={name:c.sha(value) for name,value in raw.items()}
    outputs[MANIFEST]=pretty(dict(formatVersion=1,targetSchema=19,catalogKey=source['catalogKey'],state=STATE,inputs=inputs,files={name:c.sha(value) for name,value in outputs.items()},definitions=pins))
    outputs[TARGETS]=targets_source({**inputs,**{name:c.sha(value) for name,value in outputs.items()}})
    return outputs

def run(root,write=False):
    outputs=compile_catalog(root);targets={name:c.path(root,name) for name in outputs}
    for target in targets.values():
        c.require(not target.exists() or target.is_file(),'aruba_output_invalid')
        c.require(all(not p.exists() or p.is_dir() for p in target.parents),'aruba_output_invalid')
    if write:
        staged={}
        try:
            for name,target in targets.items():
                target.parent.mkdir(parents=True,exist_ok=True);fd,temporary=tempfile.mkstemp(prefix='.catalog19-',dir=target.parent);staged[name]=temporary
                with os.fdopen(fd,'wb') as stream:stream.write(outputs[name]);stream.flush();os.fsync(stream.fileno())
            for name,target in targets.items():os.replace(staged[name],target)
        finally:
            for temporary in staged.values():
                if os.path.lexists(temporary):os.unlink(temporary)
    else:
        for name,target in targets.items():c.require(target.is_file() and target.read_bytes()==outputs[name],'aruba_catalog_stale')
    return dict(status='written' if write else 'verified',targetSchema=19,definitions=1,files={name:c.sha(value) for name,value in outputs.items()},databaseChanged=False)

def main():
    parser=argparse.ArgumentParser(description=__doc__);mode=parser.add_mutually_exclusive_group(required=True);mode.add_argument('--check',action='store_true');mode.add_argument('--write',action='store_true');args=parser.parse_args()
    try:print(json.dumps(run(ROOT,write=args.write)));return 0
    except (c.CatalogError,OSError) as error:print(json.dumps(dict(status='failed',code=str(error) if isinstance(error,c.CatalogError) else 'aruba_io_failed')));return 1
if __name__=='__main__':sys.exit(main())
