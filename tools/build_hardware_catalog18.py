"""Compile the single reviewed commercial model for SQL18; no network/import overrides."""
from __future__ import annotations

import argparse
import importlib.util
import json
import os
from pathlib import Path
import re
import sys
import tempfile

ROOT = Path(__file__).absolute().parents[1]
_spec = importlib.util.spec_from_file_location('hardware_catalog_core', ROOT/'tools/build_hardware_catalog.py')
c = importlib.util.module_from_spec(_spec); _spec.loader.exec_module(c)
SOURCE = 'development/hardware/catalog-commercial-v1.json'
LOCK = 'development/hardware/catalog-schema18.lock.json'
FACTS = 'development/hardware/startech-c6panelutp241uft.facts.json'
BASE = 'development/server/database/017-hardware-catalog.sql'
SERVER = 'development/server/src/RackClick.Server/CommercialHardwareProfiles.Generated.cs'
FRONTEND = 'development/frontend/src/hardware-commercial.generated.json'
SQL = 'development/server/database/018-commercial-hardware.sql'
MANIFEST = 'development/hardware/catalog-commercial.manifest.json'
TARGETS = 'development/server/src/RackClick.Server/CommercialHardware.Generated.targets'
STATE = 'curated_development_not_a_release'
URL = 'https://media.startech.com/cms/pdfs/c6panelutp241uft_datasheet.pdf'


def pretty(value):
    return (json.dumps(value, indent=2, ensure_ascii=True, allow_nan=False)+'\n').encode('ascii')


def validate_facts(facts, source):
    c.fields(facts, 'formatVersion model url retrieved pdfSha256 facts locators geometry rearNumbering hardwareRevision releaseDate', 'commercial_facts_invalid')
    c.require(type(facts['formatVersion']) is int and facts['formatVersion'] == 1 and
              facts['model'] == 'C6PANELUTP241UFT' and facts['url'] == URL and
              facts['retrieved'] == '2026-10-30' and isinstance(facts['pdfSha256'], str) and
              re.fullmatch('[0-9a-f]{64}', facts['pdfSha256']) is not None, 'commercial_facts_invalid')
    expected = dict(widthMm=483, heightMm=44.3, depthMm=138, rackUnits=1,
                    frontRj45=24, rearRj45=24, couplersPreinstalled=True)
    c.require(c.canonical(facts['facts']) == c.canonical(expected), 'commercial_facts_mismatch')
    c.fields(facts['locators'], 'ports dimensions', 'commercial_facts_invalid')
    for locator in facts['locators'].values(): c.text(locator, 512); c.require(bool(locator), 'commercial_facts_invalid')
    c.require(facts['geometry'] == 'Own technical schematic, no copied image or logo' and
              facts['rearNumbering'] == 'Logical pair ordinals, not asserted as printed markings' and
              facts['hardwareRevision'] is None and facts['releaseDate'] is None, 'commercial_facts_invalid')
    c.require(len(source['definitions']) == 1, 'commercial_model_not_reviewed')
    model = source['definitions'][0]
    c.require(model['key'] == 'startech-c6panelutp241uft' and model['revision'] == 'startech-20261030-v1' and
              model['identity'] == dict(manufacturer='StarTech.com', family='Cat6 feed-through', model=facts['model'], sku=facts['model']) and
              model['kind'] == 'rack' and model['rackUnits'] == expected['rackUnits'] and
              model['dimensionsMm'] == dict(width=expected['widthMm'], height=expected['heightMm'], depth=expected['depthMm']) and
              model['provenance']['source'] == facts['url'], 'commercial_facts_mismatch')
    c.require([(g['key'], g['face'], g['type'], g['count']) for g in model['groups']] ==
              [('front-copper', 'front', 'rj45', expected['frontRj45']), ('rear-copper', 'rear', 'rj45', expected['rearRj45'])] and
              model['passthrough'] == dict(frontGroup='front-copper', rearGroup='rear-copper', count=24,
                                           mapping='one-to-one', tracingAvailable=False), 'commercial_facts_mismatch')


def literal(value):
    if value is None: return 'NULL'
    if type(value) is bool: return 'true' if value else 'false'
    if type(value) in (int, float): return str(value)
    c.require(isinstance(value, str), 'commercial_sql_value_invalid')
    return "E'"+value.replace('\\', '\\\\').replace("'", "''")+"'"


def sql_source(model, digest):
    lines = ['-- Auto-generated by tools/build_hardware_catalog18.py; reviewed SQL18 only.',
             '-- SQL017 catalog immutability/publication triggers remain enabled.']
    for table in ('hardware_definition', 'hardware_mount_slot'):
        lines.append(f'ALTER TABLE {table} ALTER COLUMN height_mm TYPE numeric USING height_mm::numeric, ALTER COLUMN depth_mm TYPE numeric USING depth_mm::numeric;')
    def insert(table, columns, values):
        lines.append(f'INSERT INTO {table} ({columns}) VALUES ('+', '.join(map(literal, values))+');')
    pair = [model['key'], model['revision']]; dims = model['dimensionsMm']
    insert('hardware_definition', 'profile_key, revision, mount_kind, rack_units, width_mm, height_mm, depth_mm, color, definition_sha256, manufacturer, family, model, sku, provenance_kind, source_reference, sealed',
           pair+[model['kind'], model['rackUnits'], dims['width'], dims['height'], dims['depth'], model['color'], digest]+
           [model['identity'][key] for key in ('manufacturer', 'family', 'model', 'sku')]+
           [model['provenance']['kind'], model['provenance']['source'], False])
    for order, group in enumerate(model['groups']):
        insert('hardware_group_template', 'profile_key, revision, group_key, sort_order, type, port_count, face, name, prefix',
               pair+[group['key'], order, group['type'], group['count'], group['face'], group['name'], group['prefix']])
    passthrough = model['passthrough']
    insert('hardware_passthrough', 'profile_key, revision, front_group_key, rear_group_key, port_count',
           pair+[passthrough['frontGroup'], passthrough['rearGroup'], passthrough['count']])
    lines.append('UPDATE hardware_definition SET sealed=true WHERE profile_key='+literal(pair[0])+' AND revision='+literal(pair[1])+';')
    return ('\n'.join(lines)+'\n').encode('utf-8')


def targets_source(inputs):
    lines = ['<!-- Auto-generated by tools/build_hardware_catalog18.py. -->', '<Project>',
             '  <Target Name="VerifyCommercialHardwareCatalog" BeforeTargets="CoreCompile">', '    <ItemGroup>']
    for name, digest in inputs.items():
        lines.append('      <_CommercialCatalogInput Include="$(MSBuildThisFileDirectory)../../../../'+name+'"><ExpectedHash>'+digest+'</ExpectedHash></_CommercialCatalogInput>')
    lines += ['    </ItemGroup>',
              '    <Error Condition="!Exists(\'%(_CommercialCatalogInput.Identity)\')" Code="commercial_catalog_stale" Text="commercial_catalog_stale: missing catalog input; run tools/build_hardware_catalog18.py --check" />',
              '    <GetFileHash Files="@(_CommercialCatalogInput)" Algorithm="SHA256">',
              '      <Output TaskParameter="Items" ItemName="_CommercialCatalogHashed" />', '    </GetFileHash>',
              '    <Error Condition="\'%(_CommercialCatalogHashed.FileHash)\' != \'%(_CommercialCatalogHashed.ExpectedHash)\'" Code="commercial_catalog_stale" Text="commercial_catalog_stale: run tools/build_hardware_catalog18.py --check" />',
              '  </Target>', '</Project>', '']
    return '\n'.join(lines).encode('ascii')


def compile_catalog(root):
    raw = {name: c.path(root, name).read_bytes() for name in (SOURCE, LOCK, FACTS, BASE)}
    source = c.validate(c.load(raw[SOURCE]), commercial=True); lock = c.load(raw[LOCK])
    c.fields(lock, 'formatVersion targetSchema sourceSha256 factsSha256 baseMigrationSha256 definitions state', 'commercial_lock_invalid')
    c.require(type(lock['formatVersion']) is int and lock['formatVersion'] == 1 and
              type(lock['targetSchema']) is int and lock['targetSchema'] == 18 and lock['state'] == STATE, 'commercial_target_unsupported')
    for name, field in ((SOURCE, 'sourceSha256'), (FACTS, 'factsSha256'), (BASE, 'baseMigrationSha256')):
        c.require(c.sha(raw[name]) == lock[field], 'commercial_input_changed')
    pins = [dict(key=m['key'], revision=m['revision'], sha256=c.sha(c.canonical(m))) for m in source['definitions']]
    c.require(pins == lock['definitions'], 'commercial_definition_not_reviewed')
    validate_facts(c.load(raw[FACTS]), source)
    view = c.projection(source); view['synthetic'] = False
    for row, model in zip(view['profiles'], source['definitions']):
        row.update(identity=model['identity'], source=model['provenance']['source'], rearLogicalNumbering=True)
    outputs = {SERVER: c.server_source(source, commercial=True), FRONTEND: pretty(view),
               SQL: sql_source(source['definitions'][0], pins[0]['sha256'])}
    inputs = {name: c.sha(value) for name, value in raw.items()}
    outputs[MANIFEST] = pretty(dict(formatVersion=1, targetSchema=18, catalogKey=source['catalogKey'], state=STATE,
                                    inputs=inputs, files={name: c.sha(value) for name, value in outputs.items()}, definitions=pins))
    outputs[TARGETS] = targets_source({**inputs, **{name: c.sha(value) for name, value in outputs.items()}})
    return outputs


def run(root, write=False):
    outputs = compile_catalog(root)
    # Validate every destination before writing any derivative. Individual replaces
    # are atomic; multi-file publication is not a filesystem transaction.
    targets = {name: c.path(root, name) for name in outputs}
    for target in targets.values():
        c.require(not target.exists() or target.is_file(), 'commercial_output_invalid')
        c.require(all(not p.exists() or p.is_dir() for p in target.parents), 'commercial_output_invalid')
    if write:
        staged = {}
        try:
            for name, target in targets.items():
                target.parent.mkdir(parents=True, exist_ok=True)
                fd, temporary = tempfile.mkstemp(prefix='.catalog18-', dir=target.parent); staged[name] = temporary
                with os.fdopen(fd, 'wb') as stream:
                    stream.write(outputs[name]); stream.flush(); os.fsync(stream.fileno())
            for name, target in targets.items(): os.replace(staged[name], target)
        finally:
            for temporary in staged.values():
                if os.path.lexists(temporary): os.unlink(temporary)
    else:
        for name, target in targets.items():
            c.require(target.is_file() and target.read_bytes() == outputs[name], 'commercial_catalog_stale')
    return dict(status='written' if write else 'verified', targetSchema=18, definitions=1,
                files={name: c.sha(value) for name, value in outputs.items()}, databaseChanged=False)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--check', action='store_true'); mode.add_argument('--write', action='store_true')
    args = parser.parse_args()
    try:
        print(json.dumps(run(ROOT, write=args.write))); return 0
    except (c.CatalogError, OSError) as error:
        print(json.dumps(dict(status='failed', code=str(error) if isinstance(error, c.CatalogError) else 'commercial_io_failed'))); return 1


if __name__ == '__main__': sys.exit(main())
