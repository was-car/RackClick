import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import vm from 'node:vm';

export const sourceSha256='dda18f60915b0058a8d65329e04464599bb3b3d6e48532dc48efc213328fa7ad';
export const catalogVersion='rc9-base-v1';
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const reference='development/frontend/rc9-reference/RackClick-v0.9.0-rc9-Adoptada-2026-09-28';
const section=(source,from,to)=>{const start=source.indexOf(from),end=source.indexOf(to,start+from.length);if(start<0||end<=start)throw Error('RC9 extraction anchor missing: '+from);return source.slice(start,end)};
export function buildCatalog(source){
 if(hash(Buffer.from(source,'utf8'))!==sourceSha256)throw Error('Adopted RC9 source integrity mismatch');
 // Evaluate only hash-pinned constants and pure port constructors, never the application.
 const code=section(source,'const IR_WORDS=','const RC8_CATALOGUE=')+
  section(source,'const RC8_CATALOGUE=','function IRIcon(')+
  section(source,'const PRESETS =','const RSZ')+
  section(source,'function irPowerPorts(','function irPowerPairAllowed(')+
  section(source,'function irTemplatePorts(','/* ')+section(source,'const mkP =','/* ');
 const {presets,categories,words,make}=vm.runInNewContext(code+';({presets:PRESETS,categories:CATS,words:RC8_CATALOGUE,make:irTemplatePorts})',Object.create(null),{timeout:1000});
 if(Object.keys(presets).length!==33||categories.length!==7||new Set(categories.flatMap(c=>c.keys)).size!==33||categories.flatMap(c=>c.keys).some(k=>!presets[k]))throw Error('RC9 effective catalogue must contain 33 presets in 7 categories');
 const languages={};
 for(const language of ['en','de','es'])languages[language]={
  categories:categories.map(c=>({key:c.label,label:words[language].categories[c.label],presetKeys:[...c.keys]})),
  presets:Object.entries(presets).map(([key,preset])=>{
   const ports=make(preset,'catalogue',language);let offset=0;
   return {key,categoryKey:categories.find(c=>c.keys.includes(key)).label,label:preset.label,icon:preset.icon,color:preset.color,sizeU:preset.u,poeBudget:null,
    portGroups:preset.ports.map((group,index)=>({key:'g'+(index+1),type:group.t==='rj45_poe'?'rj45':group.t,name:'',prefix:'',sortOrder:index,
     ports:ports.slice(offset,offset+=group.n).map((p,i)=>({gn:p.gn,sortOrder:i,type:p.type,label:p.label||'',status:'free',poe:p.poe===true,watts:null,color:p.portColor??null,face:p.rackclickFace||'auto',powerRole:p.rackclickPowerRole||'unspecified',properties:{}}))}))};
  })
 };
 return {catalogVersion,source:{path:'reference/RackClick-v0.9.0-rc9-Adoptada-2026-09-28.zip!evidence/integrated-source.jsx',sha256:sourceSha256},languages};
}
export async function generateArtifacts(workspace=root){
 const source=await readFile(path.join(workspace,reference,'evidence/integrated-source.jsx'),'utf8');
 const manifest=await readFile(path.join(workspace,reference,'SHA256SUMS-PACKAGE.txt'),'utf8');
 if(!manifest.split(/\r?\n/).some(line=>line.slice(0,64)===sourceSha256&&line.slice(66).replace(/^\.\//,'')==='evidence/integrated-source.jsx'))throw Error('RC9 source is not recorded in the adopted manifest');
 const json=JSON.stringify(buildCatalog(source),null,2)+'\n',sha256=hash(Buffer.from(json,'utf8'));
 // A regular escaped C# literal preserves the final LF and exact UTF-8 JSON bytes.
 const cs='// Generated by tools/catalog/generate_rc9_catalog.mjs. Do not edit.\nnamespace RackClick.Server;\n\ninternal static class InventoryRc9CatalogData\n{\n    internal const string Sha256 = "'+sha256+'";\n    internal const string Json = '+JSON.stringify(json)+';\n}\n';
 return {json,cs,sha256};
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 if(process.argv.slice(2).some(arg=>arg!=='--check'))throw Error('Usage: node tools/catalog/generate_rc9_catalog.mjs [--check]');
 const result=await generateArtifacts(),outputs=[['development/catalog/rc9-catalog.json',result.json],['development/server/src/RackClick.Server/InventoryRc9CatalogData.g.cs',result.cs]];
 for(const [file,content] of outputs){const target=path.join(root,file);if(process.argv.includes('--check')){if(await readFile(target,'utf8')!==content)throw Error('Generated catalogue is stale: '+file)}else{await mkdir(path.dirname(target),{recursive:true});await writeFile(target,content,'utf8')}}
 console.log(JSON.stringify({status:process.argv.includes('--check')?'checked':'generated',catalogVersion,sourceSha256,catalogSha256:result.sha256,presets:33,categories:7,languages:['en','de','es'],files:outputs.map(x=>x[0])}));
}
